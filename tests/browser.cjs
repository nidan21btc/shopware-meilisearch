/* Browser interaction checks with a simulated Shopware response, no live cart. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const script = fs.readFileSync(path.join(root, 'src/Resources/public/storefront/js/search.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'src/Resources/public/storefront/css/search.css'), 'utf8');
const facetId = 'a'.repeat(32);
const fixture = `<!doctype html><html><body><button class="search-toggle-btn">Search</button><input class="header-search-input">
<dialog class="el-search" data-el-search data-endpoint="/fr/shopware-meilisearch" data-loading="Loading" data-error="Unavailable">
<button data-el-close class="el-search__back">Back</button><form data-el-query-form><input type="search" data-el-query><button type="button" data-el-clear hidden>Clear</button></form><button data-el-close class="el-search__close">Close</button><p data-el-status role="status"></p>
<div data-el-results class="el-search__body"></div><div hidden data-el-network-error><button data-el-retry>Retry</button></div></dialog>
<script>window.PluginManager={initializePlugin:async(name,selector)=>{if(name!=='AddToCart'||selector!=='[data-el-results] [data-add-to-cart]')throw Error('Unexpected plugin');window.initialized=(window.initialized||0)+1;}}</script></body></html>`;
const response = (q, params = new URLSearchParams(), english = false) => `<aside class="el-search__filters"><button data-el-suggestion="orchid">Orchid</button><div class="el-search__mobile-chips"><div class="el-search__chip-row"><button type="button" data-el-chip data-facet="category" data-value="${facetId}">Flowers</button></div></div><button type="button" class="el-search__filter-toggle" data-el-filter-toggle aria-expanded="false">Filters</button><form data-el-filters><details open data-el-facet="category"><summary>Category</summary><input data-el-facet-search><label data-el-facet-value><input type="checkbox" name="category[]" value="${facetId}">Flowers</label>${[2,3,4,5,6,7].map(n => `<label data-el-facet-value ${n>5?'hidden':''}><input type="checkbox">Category ${n}</label>`).join('')}<button type="button" data-el-show-more data-more="More" data-less="Less">More</button></details><button type="button" data-el-reset>Reset</button></form></aside>
<section data-el-result-status="Results for ${q}"><div class="el-search__toolbar"><span>87 Ergebnisse gefunden</span><button type="button" class="el-search__show-all" data-el-show-all aria-controls="el-search-product-grid" aria-expanded="false">Show all</button><label>Sortiert nach: <select data-el-sort><option value="relevance">Relevanz</option><option value="price-asc">Price</option></select></label></div><button type="button" data-el-similar aria-pressed="${params.has('similar') ? String(params.get('similar') === '1') : String(english || q.trim().split(/\s+/).filter(Boolean).length >= 2)}">Similar</button><p class="test-query">${q}</p><div id="el-search-product-grid" class="el-search__grid">${Array.from({length:12}, (_,i) => `<article class="el-search__card">Product ${i}</article>`).join('')}</div><nav class="el-search__pagination"><button data-el-page="2">Next</button></nav><form data-add-to-cart><button>Add</button></form></section>`;

(async () => {
    const browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
    try {
        const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
        let requests = [];
        let failing = false;
        await page.route('https://search.test/**', async (route) => {
            const url = new URL(route.request().url());
            if (url.pathname === '/') return route.fulfill({contentType: 'text/html', body: fixture});
            requests.push(url);
            if (failing === '503') return route.fulfill({status: 503, contentType: 'text/html', body: '<div data-el-result-status="Unavailable"><button data-el-retry>Retry</button></div>'});
            if (failing) return route.abort();
            if (url.searchParams.get('q') === 'slow') await new Promise(resolve => setTimeout(resolve, 450));
            return route.fulfill({contentType: 'text/html', body: response(url.searchParams.get('q') || '', url.searchParams)}).catch(() => {});
        });
        await page.goto('https://search.test/');
        await page.addStyleTag({content: css});
        await page.addScriptTag({type: 'module', content: script});
        if (process.env.DEBUG_SEARCH) {
            page.on('console', message => console.log(message.text()));
            await page.evaluate(() => {
                for (const type of ['focusin', 'cancel', 'close']) document.addEventListener(type, event => console.log(type, event.target.className, document.querySelector('dialog').open), true);
            });
        }
        await page.locator('.search-toggle-btn').click();
        await page.waitForSelector('[data-el-result-status]');
        assert.equal(await page.locator('dialog').evaluate(el => el.open), true);
        assert.equal(await page.locator('[data-el-query]').evaluate(el => document.activeElement === el), true);
        // The compact discovery view hides sorting until a search is entered.
        assert.equal(await page.locator('[data-el-sort]').isVisible(), false);
        assert.equal(await page.locator('dialog').evaluate(el => el.getBoundingClientRect().height < innerHeight), true);
        await page.mouse.click(100, 900);
        await page.waitForFunction(() => !document.querySelector('dialog').open);
        await page.locator('.search-toggle-btn').click();
        await page.waitForSelector('[data-el-result-status]');
        await page.locator('[data-el-filters]').evaluate(el => el.remove());
        await page.locator('[data-el-query]').fill('start');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'start');
        assert.equal(await page.locator('dialog').evaluate(el => el.classList.contains('el-search--discovery')), false);
        assert.equal(await page.locator('[data-el-facet-value]:visible').count(), 5);
        await page.locator('[data-el-show-more]').click();
        assert.equal(await page.locator('[data-el-facet-value]:visible').count(), 7);
        await page.locator('[data-el-facet-search]').fill('Category 7');
        assert.equal(await page.locator('[data-el-facet-value]:visible').count(), 1);
        await page.locator('[data-el-facet-search]').fill('');
        await page.locator('[data-el-show-more]').click();
        assert.equal(await page.locator('[data-el-facet-value]:visible').count(), 5);
        const query = page.locator('[data-el-query]');
        await query.fill('slow');
        await page.waitForTimeout(220);
        await query.fill('latest');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'latest');
        await page.waitForTimeout(500);
        assert.equal(await page.locator('.test-query').textContent(), 'latest', 'Stale response replaced new results');
        await page.locator('[data-el-similar]').click();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(requests.at(-1).searchParams.get('similar'), '1');
        await page.locator('[data-el-similar]').click();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(requests.at(-1).searchParams.get('similar'), '0');
        await query.fill('two words');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'two words');
        assert.equal(await page.locator('[data-el-similar]').getAttribute('aria-pressed'), 'true', 'Multiword default should retain weaker matches');
        await page.locator('[data-el-similar]').click();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(requests.at(-1).searchParams.get('similar'), '0', 'The customer can narrow multiword matches');
        await query.fill('latest');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'latest');
        await page.locator('[data-el-show-more]').click();
        await page.locator('[data-el-facet-search]').fill('Flowers');
        await page.locator('[name="category[]"]').check();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(await page.locator('[data-el-facet-search]').inputValue(), 'Flowers', 'Facet search text was lost');
        assert.equal(await page.locator('details[data-el-facet=category]').getAttribute('data-el-expanded'), 'true', 'Expanded facet state was lost');
        assert.equal(requests.at(-1).searchParams.get('category[]'), facetId);
        assert.equal(await page.locator('[name="category[]"]').evaluate(el => document.activeElement === el), true, 'Filter focus was lost after updating results');
        await page.locator('[data-el-sort]').selectOption('price-asc');
        await page.waitForTimeout(100);
        assert.equal(requests.at(-1).searchParams.get('sort'), 'price-asc');
        await page.locator('[data-el-page]').click();
        await page.waitForTimeout(100);
        assert.equal(requests.at(-1).searchParams.get('page'), '2');
        await page.locator('[data-el-reset]').click();
        await page.waitForTimeout(100);
        assert.equal(requests.at(-1).searchParams.has('category[]'), false);
        assert.equal(await page.locator('[data-el-price-slider]').count(), 0);
        await page.locator('[data-el-suggestion]').click();
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'orchid');
        assert.equal(await query.inputValue(), 'orchid');
        await query.fill('latest');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'latest');
        await page.keyboard.press('Escape');
        await page.waitForTimeout(50);
        assert.equal(await page.locator('dialog').evaluate(el => el.open), false);
        assert.equal(await page.locator('.search-toggle-btn').evaluate(el => document.activeElement === el), true);
        await page.locator('.header-search-input').focus();
        await page.waitForSelector('[data-el-result-status]');
        await page.keyboard.press('Escape');
        await page.waitForTimeout(100);
        assert.equal(await page.locator('dialog').evaluate(el => el.open), false, 'Focus restoration reopened dialog');
        failing = true;
        await page.locator('.search-toggle-btn').click();
        await page.waitForSelector('[data-el-network-error]:not([hidden])');
        failing = false;
        await page.locator('[data-el-retry]').click();
        await page.waitForSelector('[data-el-result-status]');
        failing = '503';
        await page.locator('[name="category[]"]').check();
        await page.waitForSelector('[data-el-results] [data-el-retry]');
        assert.equal(requests.at(-1).searchParams.get('category[]'), facetId);
        failing = false;
        await page.locator('[data-el-results] [data-el-retry]').click();
        await page.waitForSelector('[data-el-filters]');
        assert.equal(requests.at(-1).searchParams.get('category[]'), facetId, 'Retry lost the active filter');
        assert.equal(requests.at(-1).searchParams.get('q'), 'latest', 'Retry lost the search query');
        failing = '503';
        await query.fill('failed');
        await page.waitForSelector('[data-el-results] [data-el-retry]');
        failing = false;
        await page.evaluate(() => {
            const input = document.querySelector('[data-el-query]');
            input.value = 'fresh';
            input.dispatchEvent(new Event('input', {bubbles: true}));
            document.querySelector('[data-el-results] [data-el-retry]').click();
        });
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'fresh');
        assert.equal(requests.at(-1).searchParams.get('q'), 'fresh', 'Retry used a stale query while typing');
        await page.setViewportSize({width: 390, height: 844});
        await page.waitForFunction(() => document.querySelector('details')?.open === false);
        await query.fill('mobile');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'mobile');
        assert.equal(await page.locator('[data-el-show-all]').isVisible(), true, 'Mobile preview needs a show-all control');
        assert.equal(await page.locator('[data-el-sort]').isHidden(), true, 'Sort should wait for the full mobile view');
        assert.equal(await page.locator('[data-el-filter-toggle]').isHidden(), true, 'Filters should wait for the full mobile view');
        assert.equal(await page.locator('.el-search__grid .el-search__card:visible').count(), 10, 'Preview should show ten cards');
        assert.equal(await page.locator('details').evaluate(el => el.open), false);
        await page.locator('[data-el-chip]').click();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(requests.at(-1).searchParams.get('category[]'), facetId, 'Mobile chip did not apply its filter');
        assert.equal(await page.locator('[data-el-show-all]').isHidden(), true, 'Selecting a chip must open the full view');
        assert.equal(await page.locator('.el-search__grid .el-search__card:visible').count(), 12);
        const toolbarAligned = await page.locator('.el-search__toolbar').evaluate(el => {
            const count = el.querySelector('span').getBoundingClientRect();
            const sort = el.querySelector('select').getBoundingClientRect();
            return Math.abs(count.top - sort.top) < 10;
        });
        assert.equal(toolbarAligned, true, 'Mobile count and sort should fit on one line');
        await page.locator('[data-el-filter-toggle]').click();
        assert.equal(await page.locator('[data-el-filter-toggle]').getAttribute('aria-expanded'), 'true');
        assert.equal(await page.locator('[data-el-filters]').isVisible(), true, 'Mobile filters did not open');
        await page.locator('details[data-el-facet=category] summary').click();
        await page.locator('[name="category[]"]').check();
        await page.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(await page.locator('details[data-el-facet=category]').evaluate(el => el.open), true, 'Mobile facet collapsed after selection');
        assert.equal(await page.locator('[name="category[]"]').evaluate(el => document.activeElement === el), true, 'Mobile filter focus was lost');
        await page.locator('[data-el-clear]').click();
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === '');
        assert.equal(await query.inputValue(), '', 'Mobile clear did not clear the query');
        await page.locator('.el-search__back').click();
        await page.waitForFunction(() => !document.querySelector('dialog').open);
        await page.locator('.search-toggle-btn').click();
        await page.waitForSelector('[data-el-result-status]');
        await query.fill('mobile again');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'mobile again');
        const requestCount = requests.length;
        await page.locator('[data-el-show-all]').click();
        assert.equal(requests.length, requestCount, 'Show all should not issue a new search');
        assert.equal(await page.locator('[data-el-sort]').evaluate(el => document.activeElement === el), true, 'Focus should move to the revealed controls');
        assert.equal(await page.locator('.el-search__grid .el-search__card:visible').count(), 12);
        await query.fill('changed');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'changed');
        assert.equal(await page.locator('[data-el-show-all]').isHidden(), true, 'Full view should persist when the query changes');
        await page.locator('[data-el-clear]').click();
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === '');
        await query.fill('after clear');
        await page.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'after clear');
        assert.equal(await page.locator('[data-el-show-all]').isHidden(), true, 'Full view should persist after clearing the query');
        assert.equal(await page.locator('dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'Mobile horizontal overflow');
        assert.equal(requests.every(url => url.pathname === '/fr/shopware-meilisearch'), true, 'Endpoint language changed');
        assert.equal(requests.some(url => url.searchParams.has('languageId') || url.searchParams.has('index')), false, 'Browser chooses engine scope');
        const english = await browser.newPage();
        const englishRequests = [];
        await english.route('https://english.test/**', async route => {
            const url = new URL(route.request().url());
            if (url.pathname === '/') return route.fulfill({contentType: 'text/html', body: fixture.replace('data-el-search data-endpoint', 'data-el-search data-locale="en-GB" data-endpoint')});
            englishRequests.push(url);
            return route.fulfill({contentType: 'text/html', body: response(url.searchParams.get('q') || '', url.searchParams, true)});
        });
        await english.goto('https://english.test/');
        await english.addStyleTag({content: css});
        await english.addScriptTag({type: 'module', content: script});
        await english.locator('.search-toggle-btn').click();
        await english.waitForSelector('[data-el-result-status]');
        await english.locator('[data-el-query]').fill('word');
        await english.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'word');
        assert.equal(englishRequests.at(-1).searchParams.has('similar'), false, 'English default should be chosen by the server');
        assert.equal(await english.locator('[data-el-similar]').getAttribute('aria-pressed'), 'true');
        await english.locator('[data-el-similar]').click();
        await english.waitForFunction(() => document.querySelector('[data-el-results]').getAttribute('aria-busy') === 'false');
        assert.equal(englishRequests.at(-1).searchParams.get('similar'), '0', 'English can explicitly hide similar results');
        await english.locator('[data-el-query]').fill('next');
        await english.waitForFunction(() => document.querySelector('.test-query')?.textContent === 'next');
        assert.equal(englishRequests.at(-1).searchParams.has('similar'), false, 'New English search should restore the server default');
        assert.equal(await english.locator('[data-el-similar]').getAttribute('aria-pressed'), 'true');
        await english.close();
        console.log('Browser checks passed: opening, focus, stale responses, filters, sort, paging, reset, Escape, retry, mobile, language endpoint.');
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
